    private static string FormatDominantManageBonusLayout(IReadOnlyList<PayloadWithFile> payloads)
    {
        if (payloads.Count == 0)
        {
            return "-";
        }

        var group = payloads
            .GroupBy(entry => new
            {
                Byte9Field = PayloadWordAtByteOffset(entry.Payload.PayloadHex, 9),
                Byte11Value = PayloadWordAtByteOffset(entry.Payload.PayloadHex, 11),
                Byte15Value = PayloadWordAtByteOffset(entry.Payload.PayloadHex, 15)
            })
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key.Byte9Field, StringComparer.OrdinalIgnoreCase)
            .First();

        return $"`{group.Key.Byte9Field}` / `{group.Key.Byte11Value}` / `{group.Key.Byte15Value}` ({group.Count()})";
    }

    private static string PayloadWordAtByteOffset(string payloadHex, int byteOffset)
