                group.Key.Text,
                group.Count(),
                group.First()))
            .OrderByDescending(group => group.Count)
            .ThenBy(group => group.Classification)
            .ThenBy(group => group.Text, StringComparer.OrdinalIgnoreCase)
            .ToArray();
