    private static void AppendVendorInventoryCorrelations(StringBuilder builder, PacketResearchReport report)
    {
        if (report.VendorInventoryEntries.Count == 0)
        {
            return;
        }

        Dictionary<uint, int> dumpInteractionCounts = report.PacketDumpFiles
            .SelectMany(file => file.Protocol04InteractionPayloads)
            .GroupBy(payload => payload.ObjectId)
            .ToDictionary(group => group.Key, group => group.Count());
        Dictionary<uint, int> externalCommandCounts = report.Protocol04InteractionCommandExamples
            .GroupBy(example => example.ObjectId)
            .ToDictionary(group => group.Key, group => group.Count());
        HashSet<uint> interactionObjectIds = new(dumpInteractionCounts.Keys.Concat(externalCommandCounts.Keys));
        VendorInventoryEntry[] matches = report.VendorInventoryEntries
            .Where(entry => interactionObjectIds.Contains(entry.VendorStaticId))
            .ToArray();
        if (matches.Length == 0)
        {
            return;
        }

        builder.AppendLine("## Vendor Inventory Object Correlations");
        builder.AppendLine();
        builder.AppendLine("This joins decoded object-interaction object ids against tracked `data/vendor_items.csv` rows. The vendor list was parser-derived from old logs and is incomplete, so a match is a lead that the static id may be vendor-related, not proof of a complete vendor exchange.");
        builder.AppendLine();
        builder.AppendLine("| Static object id | Metr ids | Vendor rows | Packet-dump interactions | External command interactions | Item counts | Sample items | Sample vendor row |");
        builder.AppendLine("| ---: | --- | ---: | ---: | ---: | --- | --- | --- |");
        foreach (var group in matches
            .GroupBy(entry => entry.VendorStaticId)
            .OrderByDescending(group => dumpInteractionCounts.GetValueOrDefault(group.Key) + externalCommandCounts.GetValueOrDefault(group.Key))
            .ThenBy(group => group.Key))
        {
            VendorInventoryEntry sample = group.First();
            string metrIds = string.Join(", ", group.Select(entry => entry.MetrId).Distinct().OrderBy(value => value));
            string itemCounts = string.Join(", ", group.Select(entry => entry.Items.Count).Distinct().OrderBy(value => value));
            string sampleItems = string.Join(", ", group.SelectMany(entry => entry.Items).Distinct().Take(8));
            builder.AppendLine(
                $"| {group.Key} | {metrIds} | {group.Count()} | {dumpInteractionCounts.GetValueOrDefault(group.Key)} | {externalCommandCounts.GetValueOrDefault(group.Key)} | {itemCounts} | `{sampleItems}` | `{sample.File}:{sample.Line}` |");
        }

        builder.AppendLine();
    }

    private static void AppendProtocol04SequenceSummary(StringBuilder builder, PacketResearchReport report)
    {
        var sequences = report.PacketDumpFiles
            .SelectMany(file => file.Protocol04PacketSequences.Select(sequence => new Protocol04SequenceWithFile(file.File, sequence)))
            .Where(entry => entry.Sequence.Direction != "client")
            .Where(entry => entry.Sequence.Headers.Any(header =>
                header.Equals("80 b2", StringComparison.OrdinalIgnoreCase)
                || header.Equals("80 bc", StringComparison.OrdinalIgnoreCase)))
            .ToArray();

        if (sequences.Length == 0)
        {
            return;
        }

        int bothCount = sequences.Count(entry =>
            entry.Sequence.Headers.Any(header => header.Equals("80 b2", StringComparison.OrdinalIgnoreCase))
            && entry.Sequence.Headers.Any(header => header.Equals("80 bc", StringComparison.OrdinalIgnoreCase)));

        builder.AppendLine("## Protocol 04 Server State Sequences");
        builder.AppendLine();
        builder.AppendLine("This groups top-level server protocol 04 packet header sequences that contain `80 b2` and/or `80 bc`. It preserves packet order so repeated state-bundle flows can be separated from isolated RPC hits.");
        builder.AppendLine();
        builder.AppendLine($"- State-related protocol 04 packets: {sequences.Length}");
        builder.AppendLine($"- Packets containing both `80 b2` and `80 bc`: {bothCount}");
        builder.AppendLine();
        builder.AppendLine("| Header sequence | Count | Contains `80 b2` | Contains `80 bc` | Sample |");
        builder.AppendLine("| --- | ---: | --- | --- | --- |");
        foreach (var group in sequences
            .GroupBy(entry => FormatSequence(entry.Sequence.Headers), StringComparer.OrdinalIgnoreCase)
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key)
            .Take(25))
        {
            Protocol04SequenceWithFile sample = group.First();
            bool hasB2 = sample.Sequence.Headers.Any(header => header.Equals("80 b2", StringComparison.OrdinalIgnoreCase));
            bool hasBc = sample.Sequence.Headers.Any(header => header.Equals("80 bc", StringComparison.OrdinalIgnoreCase));
            builder.AppendLine(
                $"| `{group.Key}` | {group.Count()} | {FormatBoolean(hasB2)} | {FormatBoolean(hasBc)} | `{sample.File}:{sample.Sequence.Line}` |");
        }

        builder.AppendLine();
        AppendProtocol04StateFieldLinks(builder, report);
    }

    private static void AppendProtocol04StateFieldLinks(StringBuilder builder, PacketResearchReport report)
    {
        PlayerAttributePayloadWithFile[] b2Payloads = report.PacketDumpFiles
            .SelectMany(file => file.PlayerAttributePayloads.Select(payload => new PlayerAttributePayloadWithFile(file.File, payload)))
            .ToArray();
        PayloadWithFile[] bcPayloads = report.PacketDumpFiles
            .SelectMany(file => file.ManageBonusPayloads.Select(payload => new PayloadWithFile(file.File, payload)))
            .ToArray();

        var b2ByPacket = b2Payloads
            .GroupBy(entry => new PacketLocation(entry.File, entry.Payload.Line))
            .ToDictionary(group => group.Key, group => group.ToArray());
        var bcByPacket = bcPayloads
            .GroupBy(entry => new PacketLocation(entry.File, entry.Payload.Line))
            .ToDictionary(group => group.Key, group => group.ToArray());

        List<StateFieldLink> links = new();
        foreach ((PacketLocation packet, PlayerAttributePayloadWithFile[] b2Entries) in b2ByPacket)
        {
            if (!bcByPacket.TryGetValue(packet, out PayloadWithFile[]? bcEntries))
            {
                continue;
            }

            foreach (PlayerAttributePayloadWithFile b2 in b2Entries)
            {
                foreach (PayloadWithFile bc in bcEntries)
                {
                    if (b2.Payload.Field0Value != bc.Payload.Field1Value)
                    {
                        continue;
                    }

                    links.Add(new StateFieldLink(packet, b2, bc));
                }
            }
        }

        if (links.Count == 0)
        {
            return;
        }

        builder.AppendLine("### Cross-Family State Field Links");
        builder.AppendLine();
        builder.AppendLine("This links `80 b2` field 0 with `80 bc` field 1 when both values appear in the same top-level protocol 04 packet. These are high-priority semantic leads because they connect the short player-attribute/ability-load form to the longer manage-bonus form.");
        builder.AppendLine();
        builder.AppendLine("| Shared field | Packet count | Pair count | Sample | `80 b2` payload | `80 bc` payload |");
        builder.AppendLine("| --- | ---: | ---: | --- | --- | --- |");
        foreach (var group in links
            .GroupBy(link => new { link.B2.Payload.Field0Value, link.B2.Payload.Field0, link.Bc.Payload.Field1 })
            .OrderByDescending(group => group.Select(link => link.Packet).Distinct().Count())
            .ThenBy(group => group.Key.Field0Value)
            .Take(20))
        {
            StateFieldLink sample = group.First();
            int packetCount = group.Select(link => link.Packet).Distinct().Count();
            builder.AppendLine(
                $"| `{group.Key.Field0}` ({group.Key.Field0Value}) | {packetCount} | {group.Count()} | `{sample.Packet.File}:{sample.Packet.Line}` | `{sample.B2.Payload.PayloadHex}` | `{sample.Bc.Payload.PayloadHex}` |");
        }

        builder.AppendLine();
        AppendLinkedStateValueConsistency(builder, links);
    }

    private static void AppendLinkedStateValueConsistency(StringBuilder builder, IReadOnlyList<StateFieldLink> links)
    {
        var comparisons = links
            .Select(link => new LinkedStateValueComparison(
                link.Packet,
                link.B2.Payload.Field0,
                link.B2.Payload.Field1,
                PayloadWordAtByteOffset(link.Bc.Payload.PayloadHex, 9),
                PayloadWordAtByteOffset(link.Bc.Payload.PayloadHex, 11),
                link.B2.Payload.PayloadHex,
                link.Bc.Payload.PayloadHex))
            .ToArray();

        int repeatedFieldCount = comparisons.Count(comparison =>
            comparison.B2Field.Equals(comparison.BcByte9Field, StringComparison.OrdinalIgnoreCase));
        int matchingValueCount = comparisons.Count(comparison =>
            comparison.B2Value.Equals(comparison.BcByte11Value, StringComparison.OrdinalIgnoreCase));

        builder.AppendLine("### Linked Short/Long Field-Value Consistency");
        builder.AppendLine();
        builder.AppendLine("This compares each linked `80 b2` payload with the embedded field/value bytes inside its paired `80 bc` payload. In the dominant pattern, `80 bc` repeats the linked field at payload byte offset 9 and repeats the `80 b2` field 1 value at payload byte offset 11.");
        builder.AppendLine();
        builder.AppendLine($"- Same-packet field links: {comparisons.Length}");
        builder.AppendLine($"- Links with repeated `80 bc` byte 9 field: {repeatedFieldCount}");
        builder.AppendLine($"- Links with matching `80 bc` byte 11 value: {matchingValueCount}");
        builder.AppendLine();
        builder.AppendLine("| `80 b2` field | `80 b2` value | `80 bc` byte 9 field | `80 bc` byte 11 value | Pair count | Packet count | Sample |");
        builder.AppendLine("| --- | --- | --- | --- | ---: | ---: | --- |");
        foreach (var group in comparisons
            .GroupBy(comparison => new
            {
                comparison.B2Field,
                comparison.B2Value,
                comparison.BcByte9Field,
                comparison.BcByte11Value
            })
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key.B2Field, StringComparer.OrdinalIgnoreCase)
            .ThenBy(group => group.Key.B2Value, StringComparer.OrdinalIgnoreCase)
            .Take(20))
        {
            LinkedStateValueComparison sample = group.First();
            int packetCount = group.Select(comparison => comparison.Packet).Distinct().Count();
            builder.AppendLine(
                $"| `{group.Key.B2Field}` | `{group.Key.B2Value}` | `{group.Key.BcByte9Field}` | `{group.Key.BcByte11Value}` | {group.Count()} | {packetCount} | `{sample.Packet.File}:{sample.Packet.Line}` |");
        }

        builder.AppendLine();
    }

    private static void AppendProtocol03ObjectViewSummary(StringBuilder builder, PacketResearchReport report)
    {
        var samples = report.PacketDumpFiles
            .SelectMany(file => file.Protocol03ObjectViews.Select(sample => new Protocol03SampleWithFile(file.File, sample)))
            .ToArray();

        if (samples.Length == 0)
        {
            return;
        }

        builder.AppendLine("## Protocol 03 Object View Signatures");
        builder.AppendLine();
        builder.AppendLine("This decodes object-view updates in top-level protocol 03 packets using local `WorldPacket` framing, Rajko `MessageTypes.cpp` examples, and Rajko client movement parsing. It is intentionally conservative: classifications are packet-family labels, not full attribute decodes, and variable-length selectors stay marked as partial.");
        builder.AppendLine();
        int completeSamples = samples.Count(entry => entry.Sample.Complete);
        int knownSegments = samples.Sum(entry => entry.Sample.ParsedUpdateCount);
        int secondaryMovementWrappers = samples.Sum(entry => entry.Sample.Segments.Count(segment => segment.Classification == "secondary movement wrapper"));
        builder.AppendLine($"- Object messages parsed: {samples.Length}");
        builder.AppendLine($"- Fully segmented messages: {completeSamples}");
        builder.AppendLine($"- Known selector segments: {knownSegments}");
        builder.AppendLine($"- Secondary movement wrapper segments: {secondaryMovementWrappers}");
        builder.AppendLine();
        builder.AppendLine("| Classification | Update count | First selector | Count | Fully segmented | Sample | Prefix |");
        builder.AppendLine("| --- | ---: | --- | ---: | ---: | --- | --- |");
        foreach (var group in samples
            .GroupBy(entry => new
            {
                entry.Sample.Classification,
                entry.Sample.UpdateCount,
                entry.Sample.FirstSelector
            })
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key.Classification)
            .ThenBy(group => group.Key.UpdateCount)
            .Take(25))
        {
            var sample = group.First();
            builder.AppendLine(
                $"| {group.Key.Classification} | {group.Key.UpdateCount} | `{group.Key.FirstSelector}` | {group.Count()} | {group.Count(entry => entry.Sample.Complete)} | `{sample.File}:{sample.Sample.Line}` | `{sample.Sample.PrefixHex}` |");
        }

        builder.AppendLine();
        builder.AppendLine("### Protocol 03 Selector Sizes");
        builder.AppendLine();
        builder.AppendLine("| Selector | Segment classification | Payload/tail bytes | Known length | Count | Sample | Payload prefix |");
        builder.AppendLine("| --- | --- | ---: | --- | ---: | --- | --- |");
        foreach (var group in samples
            .SelectMany(entry => entry.Sample.Segments.Select(segment => new Protocol03SegmentWithFile(entry.File, entry.Sample.Line, segment)))
            .GroupBy(entry => new
            {
                entry.Segment.Selector,
                entry.Segment.Classification,
                entry.Segment.PayloadBytes,
                entry.Segment.IsKnownLength
            })
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key.Selector, StringComparer.OrdinalIgnoreCase)
            .Take(25))
        {
            Protocol03SegmentWithFile sample = group
                .OrderByDescending(entry => entry.Segment.PayloadPrefixHex.Length > 0)
                .First();
            string knownLength = group.Key.IsKnownLength ? "yes" : "no";
            builder.AppendLine(
                $"| `{group.Key.Selector}` | {group.Key.Classification} | {group.Key.PayloadBytes} | {knownLength} | {group.Count()} | `{sample.File}:{sample.Line}` | `{sample.Segment.PayloadPrefixHex}` |");
        }

        builder.AppendLine();
        builder.AppendLine("### Protocol 03 Files");
        builder.AppendLine();
        builder.AppendLine("| File | Parsed object-view packets | Fully segmented | Top classification |");
        builder.AppendLine("| --- | ---: | ---: | --- |");
        foreach (var fileGroup in samples
            .GroupBy(entry => entry.File, StringComparer.OrdinalIgnoreCase)
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key)
            .Take(15))
        {
            var topClassification = fileGroup
