    private static bool IsHeaderLabelMatch(string label, RpcHeaderEntry header)
    {
        return label.StartsWith(header.EncodedHeader + " ", StringComparison.OrdinalIgnoreCase)
            && label.Contains(header.Name, StringComparison.OrdinalIgnoreCase)
            && label.Contains($"[{header.Protocol} {header.Direction}]", StringComparison.OrdinalIgnoreCase);
    }

    private static string FormatHeaderSamples(IReadOnlyList<PacketDumpFileSummary> files, RpcHeaderEntry header)
    {
        List<string> samples = new();
        foreach (PacketDumpFileSummary file in files)
        {
            foreach ((string label, IReadOnlyList<int> lines) in file.KnownHeaderSampleLines)
            {
                if (!IsHeaderLabelMatch(label, header))
                {
                    continue;
                }

                samples.Add($"`{file.File}:{string.Join(",", lines.Take(3))}`");
                if (samples.Count == 3)
                {
                    return string.Join("<br>", samples);
                }
            }
        }

        return samples.Count == 0 ? "-" : string.Join("<br>", samples);
    }

    private static string[] AttributeCandidates(
        IReadOnlyList<AttributeDefinition> attributes,
        int fieldValue,
        bool creationIndex)
    {
        return attributes
            .Where(attribute => creationIndex ? attribute.CreationIndex == fieldValue : attribute.UpdateIndex == fieldValue)
            .GroupBy(attribute => attribute.AttributeName, StringComparer.OrdinalIgnoreCase)
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key)
            .Take(8)
            .Select(group => $"{group.Key} ({group.Count()})")
            .ToArray();
    }

    private static string FormatCandidateList(IReadOnlyList<string> candidates)
    {
        return candidates.Count == 0
            ? "-"
            : string.Join("<br>", candidates);
    }

    private static string FormatDominantManageBonusLayout(IReadOnlyList<PayloadWithFile> payloads)
    {
        if (payloads.Count == 0)
        {
            return "-";
        }

        var group = payloads
            .GroupBy(entry => new
            {
                Byte9Field = PayloadWordAtByteOffset(entry.Payload.PayloadHex, 9),
                Byte11Value = PayloadWordAtByteOffset(entry.Payload.PayloadHex, 11),
                Byte15Value = PayloadWordAtByteOffset(entry.Payload.PayloadHex, 15)
            })
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key.Byte9Field, StringComparer.OrdinalIgnoreCase)
            .First();

        return $"`{group.Key.Byte9Field}` / `{group.Key.Byte11Value}` / `{group.Key.Byte15Value}` ({group.Count()})";
    }

    private static string PayloadWordAtByteOffset(string payloadHex, int byteOffset)
    {
        string[] bytes = payloadHex.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        return byteOffset >= 0 && byteOffset + 1 < bytes.Length
            ? $"{bytes[byteOffset]} {bytes[byteOffset + 1]}"
            : "-";
    }

    private static bool IsInteractionAttributeName(string name)
    {
        string[] terms =
        {
            "buy",
