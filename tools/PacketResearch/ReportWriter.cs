using System.Text;
using System.Text.Json;

namespace MxoHd.PacketResearch;

public static class ReportWriter
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true
    };

    public static void WriteJson(PacketResearchReport report, string path)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, JsonSerializer.Serialize(report, JsonOptions));
    }

    public static void WriteMarkdown(PacketResearchReport report, string path)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, ToMarkdown(report));
    }

    public static string ToMarkdown(PacketResearchReport report)
    {
        StringBuilder builder = new();
        builder.AppendLine("# Packet Research Summary");
        builder.AppendLine();
        builder.AppendLine("Generated by `tools/PacketResearch`. This file summarizes packet evidence without copying raw dump bodies into the report.");
        builder.AppendLine();
        builder.AppendLine("## Inputs");
        builder.AppendLine();
        builder.AppendLine($"- Repository: `{report.RepositoryRoot}`");
        builder.AppendLine($"- Packet dump roots: {FormatList(report.PacketDumpRoots)}");
        builder.AppendLine($"- Rajko MxOEmu source: `{report.RajkoSourceRoot ?? "not provided"}`");
        builder.AppendLine($"- External source roots: {FormatList(report.ExternalSourceRoots)}");
        builder.AppendLine();

        int packetLines = report.PacketDumpFiles.Sum(file => file.PacketLikeLines);
        builder.AppendLine("## Totals");
        builder.AppendLine();
        builder.AppendLine($"- Local RPC headers: {report.LocalHeaders.Count}");
        builder.AppendLine($"- Local attribute definitions: {report.AttributeDefinitions.Count}");
        builder.AppendLine($"- Community FX definitions: {report.FxDefinitions.Count}");
        builder.AppendLine($"- Rajko RPC dispatch entries: {report.RajkoRpcHeaders.Count}");
        builder.AppendLine($"- Hardcoded command examples: {report.HardcodedCommands.Count}");
        builder.AppendLine($"- Hardcoded protocol 03 examples: {report.HardcodedProtocol03Examples.Count}");
        builder.AppendLine($"- External object-interaction command examples: {report.Protocol04InteractionCommandExamples.Count}");
        builder.AppendLine($"- Vendor inventory rows: {report.VendorInventoryEntries.Count}");
        builder.AppendLine($"- Protocol 04 interaction payloads: {report.PacketDumpFiles.Sum(file => file.Protocol04InteractionPayloads.Count)}");
        builder.AppendLine($"- Packet dump files with packet-like lines: {report.PacketDumpFiles.Count}");
        builder.AppendLine($"- Packet-like lines: {packetLines}");
        builder.AppendLine();

        AppendRajkoComparison(builder, report);
        AppendPacketDumpSummary(builder, report);
        AppendProtocol04InteractionSummary(builder, report);
        AppendProtocol04InteractionCommandExamples(builder, report);
        AppendVendorInventoryCorrelations(builder, report);
        AppendProtocol04SequenceSummary(builder, report);
        AppendProtocol03ObjectViewSummary(builder, report);
        AppendHardcodedProtocol03Examples(builder, report);
        AppendPlayerAttributePayloadSummary(builder, report);
        AppendManageBonusPayloadSummary(builder, report);
        AppendVendorSignals(builder, report);

        return builder.ToString();
    }

    private static void AppendRajkoComparison(StringBuilder builder, PacketResearchReport report)
    {
        if (report.RajkoComparisons.Count == 0)
        {
            builder.AppendLine("## Rajko RPC Dispatch Map");
            builder.AppendLine();
            builder.AppendLine("No Rajko source root was provided, so no external dispatch map was compared.");
            builder.AppendLine();
            return;
        }

        builder.AppendLine("## Rajko RPC Dispatch Map");
        builder.AppendLine();
        builder.AppendLine("| External raw | Handler | Match | Local header | Local name |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (RpcComparison comparison in report.RajkoComparisons)
        {
            builder.AppendLine(
                $"| `{comparison.External.RawHeader}` | `{comparison.External.Handler}` | {comparison.MatchKind} | `{comparison.Local?.EncodedHeader ?? "-"}` | {comparison.Local?.Name ?? "-"} |");
        }

        builder.AppendLine();
    }

    private static void AppendPacketDumpSummary(StringBuilder builder, PacketResearchReport report)
    {
        builder.AppendLine("## Packet Dump Coverage");
        builder.AppendLine();
        if (report.PacketDumpFiles.Count == 0)
        {
            builder.AppendLine("No packet dumps were parsed.");
            builder.AppendLine();
            return;
        }

        Dictionary<string, int> protocolTotals = new(StringComparer.OrdinalIgnoreCase);
        Dictionary<string, int> rpcTotals = new(StringComparer.OrdinalIgnoreCase);
        Dictionary<string, int> knownHeaderTotals = new(StringComparer.OrdinalIgnoreCase);
        foreach (PacketDumpFileSummary file in report.PacketDumpFiles)
        {
            AddCounts(protocolTotals, file.ProtocolCounts);
            AddCounts(rpcTotals, file.RpcHeaderCounts);
            AddCounts(knownHeaderTotals, file.KnownHeaderCounts);
        }

        builder.AppendLine("### Protocol Counts");
        builder.AppendLine();
        builder.AppendLine("| Protocol | Lines |");
        builder.AppendLine("| --- | ---: |");
        foreach ((string protocol, int count) in protocolTotals.OrderByDescending(entry => entry.Value))
        {
            builder.AppendLine($"| `{protocol}` | {count} |");
        }

        builder.AppendLine();
        builder.AppendLine("### Protocol 04 Header Hits");
        builder.AppendLine();
        if (rpcTotals.Count == 0)
        {
            builder.AppendLine("No protocol 04 headers were detected with the current heuristic.");
            builder.AppendLine();
        }
        else
        {
            builder.AppendLine("| Header | Count |");
            builder.AppendLine("| --- | ---: |");
            foreach ((string header, int count) in rpcTotals.OrderByDescending(entry => entry.Value).ThenBy(entry => entry.Key))
            {
                builder.AppendLine($"| `{header}` | {count} |");
            }

            builder.AppendLine();
        }

        builder.AppendLine("### Embedded Known Header Candidates");
        builder.AppendLine();
        builder.AppendLine("This scan searches every packet-like line for known two-byte local headers. Treat these as leads for manual decoding, not proof that the surrounding bytes are fully understood.");
        builder.AppendLine();
        if (knownHeaderTotals.Count == 0)
        {
            builder.AppendLine("No embedded known headers were detected.");
            builder.AppendLine();
        }
        else
        {
            builder.AppendLine("| Header | Count |");
            builder.AppendLine("| --- | ---: |");
            foreach ((string header, int count) in knownHeaderTotals.OrderByDescending(entry => entry.Value).ThenBy(entry => entry.Key).Take(30))
            {
                builder.AppendLine($"| `{header}` | {count} |");
            }

            builder.AppendLine();
        }

        builder.AppendLine("### Largest Parsed Files");
        builder.AppendLine();
        builder.AppendLine("| File | Packet-like lines | Protocol 04 hits | Embedded header candidates |");
        builder.AppendLine("| --- | ---: | ---: | ---: |");
        foreach (PacketDumpFileSummary file in report.PacketDumpFiles.OrderByDescending(file => file.PacketLikeLines).Take(15))
        {
            builder.AppendLine($"| `{file.File}` | {file.PacketLikeLines} | {file.RpcHeaderCounts.Values.Sum()} | {file.KnownHeaderCounts.Values.Sum()} |");
        }

        builder.AppendLine();
    }

    private static void AppendProtocol04InteractionSummary(StringBuilder builder, PacketResearchReport report)
    {
        Protocol04InteractionWithFile[] interactions = report.PacketDumpFiles
            .SelectMany(file => file.Protocol04InteractionPayloads.Select(payload => new Protocol04InteractionWithFile(file.File, payload)))
            .ToArray();

        if (interactions.Length == 0)
        {
            return;
        }

        builder.AppendLine("## Protocol 04 Object Interaction Payloads");
        builder.AppendLine();
        builder.AppendLine("This decodes the payload shape used by the local object-interaction handlers: four-byte object id, two-byte sector window from that id, and one-byte object type. Type names are local handler labels, so they are interaction leads rather than complete protocol semantics.");
        builder.AppendLine();
        builder.AppendLine("| Header | Kind | Object type | Local type label | Count | Distinct object ids | Sample | Sample payload |");
        builder.AppendLine("| --- | --- | ---: | --- | ---: | ---: | --- | --- |");
        foreach (var group in interactions
            .GroupBy(entry => new
            {
                entry.Payload.RawHeader,
                entry.Payload.InteractionKind,
                entry.Payload.ObjectType,
                entry.Payload.ObjectTypeName
            })
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key.RawHeader)
            .ThenBy(group => group.Key.ObjectType))
        {
            Protocol04InteractionWithFile sample = group.First();
            builder.AppendLine(
                $"| `{group.Key.RawHeader}` | {group.Key.InteractionKind} | {group.Key.ObjectType} | {group.Key.ObjectTypeName} | {group.Count()} | {group.Select(entry => entry.Payload.ObjectId).Distinct().Count()} | `{sample.File}:{sample.Payload.Line}` | `{sample.Payload.PayloadHex}` |");
        }

        builder.AppendLine();

        builder.AppendLine("### Repeated Interaction Object IDs");
        builder.AppendLine();
        builder.AppendLine("| Object id | Sector | Kind | Object type | Local type label | Count | Sample |");
        builder.AppendLine("| ---: | ---: | --- | ---: | --- | ---: | --- |");
        foreach (var group in interactions
            .GroupBy(entry => new
            {
                entry.Payload.ObjectId,
                entry.Payload.SectorId,
                entry.Payload.InteractionKind,
                entry.Payload.ObjectType,
                entry.Payload.ObjectTypeName
            })
            .OrderByDescending(group => group.Count())
            .ThenBy(group => group.Key.ObjectId)
            .Take(25))
        {
            Protocol04InteractionWithFile sample = group.First();
            builder.AppendLine(
                $"| {group.Key.ObjectId} | {group.Key.SectorId} | {group.Key.InteractionKind} | {group.Key.ObjectType} | {group.Key.ObjectTypeName} | {group.Count()} | `{sample.File}:{sample.Payload.Line}` |");
        }

        builder.AppendLine();
    }

