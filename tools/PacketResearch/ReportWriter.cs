    private static string FormatMovementStateTailTagRange(IEnumerable<Protocol03MovementStateTailLeadWithFile> leads)
    {
        uint[] values = leads.Select(entry => entry.Lead.TagValue).ToArray();
        if (values.Length == 0)
        {
